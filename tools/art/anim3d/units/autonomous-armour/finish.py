"""Actual Cycles UV AO + Pointiness bakes drive dirt and chipped edge colour.
Rebuild first when geometry changes. Image pixels are generated by Blender geometry bakes.
"""
import bpy,os,json,sys
sys.path.insert(0,str(__import__("pathlib").Path(__file__).resolve().parent))
from common import MASTER, ASSETS, log
from pathlib import Path
R=Path(os.environ['ANIM_ROOT']);M=MASTER;out=M/'textures/baked';out.mkdir(parents=True,exist_ok=True)
bpy.ops.wm.open_mainfile(filepath=str(M/'model.blend'))
for o in bpy.data.objects:
    if 'effect' in o:o.hide_render=True;o.scale=(1,)*3
sc=bpy.context.scene;sc.render.engine='CYCLES';sc.cycles.device='CPU';sc.cycles.samples=8
sc.render.threads_mode='FIXED';sc.render.threads=3;sc.render.bake.margin=8;sc.render.bake.use_clear=True

fill=bpy.data.images.load(str(ASSETS/'painted-fill.png'))
paint=bpy.data.materials['MAT-worn grey olive paint'];n=paint.node_tree.nodes;l=paint.node_tree.links;s=n.get('Principled BSDF')
t=n.new('ShaderNodeTexImage');t.image=fill;t.projection='BOX';t.projection_blend=.35
uv=n.new('ShaderNodeTexCoord');l.new(uv.outputs['Generated'],t.inputs['Vector']);l.new(t.outputs[0],s.inputs['Base Color'])
records=[]
for idx,name in enumerate(['GEO-sloped hull','GEO-angular turret','GEO-lower hull']):
    obj=bpy.data.objects[name];bpy.ops.object.select_all(action='DESELECT');obj.select_set(True);bpy.context.view_layer.objects.active=obj
    bpy.ops.object.mode_set(mode='EDIT');bpy.ops.mesh.select_all(action='SELECT');bpy.ops.uv.smart_project(angle_limit=1.15,island_margin=.035);bpy.ops.object.mode_set(mode='OBJECT')
    mat=obj.data.materials[0].copy();mat.name=name+' • baked pigment';obj.data.materials.clear();obj.data.materials.append(mat)
    n=mat.node_tree.nodes;l=mat.node_tree.links;s=n.get('Principled BSDF');output=next(x for x in n if x.type=='OUTPUT_MATERIAL');maps={}
    for mode in ['AO','curvature']:
        im=bpy.data.images.new(f'autonomous-armour {idx} {mode}',512,512,alpha=False);im.colorspace_settings.name='Non-Color'
        tex=n.new('ShaderNodeTexImage');tex.image=im;n.active=tex
        old=output.inputs['Surface'].links[0].from_socket
        if mode=='curvature':
            geom=n.new('ShaderNodeNewGeometry');emit=n.new('ShaderNodeEmission');l.new(geom.outputs['Pointiness'],emit.inputs['Color']);l.new(emit.outputs[0],output.inputs['Surface'])
        bpy.ops.object.bake(type='AO' if mode=='AO' else 'EMIT')
        if mode=='curvature':l.new(old,output.inputs['Surface']);n.remove(emit);n.remove(geom)
        im.filepath_raw=str(out/f'{idx}-{mode}.png');im.file_format='PNG';im.save();maps[mode]=tex
    base=s.inputs['Base Color'].links[0].from_socket
    grime=n.new('ShaderNodeMixRGB');grime.blend_type='MULTIPLY';grime.inputs[0].default_value=.7;l.new(base,grime.inputs[1]);l.new(maps['AO'].outputs['Color'],grime.inputs[2])
    ramp=n.new('ShaderNodeValToRGB');ramp.color_ramp.elements[0].position=.495;ramp.color_ramp.elements[0].color=(0,0,0,1);ramp.color_ramp.elements[1].position=.555;ramp.color_ramp.elements[1].color=(.75,.75,.75,1);l.new(maps['curvature'].outputs[0],ramp.inputs[0])
    chips=n.new('ShaderNodeTexNoise');chips.inputs['Scale'].default_value=85;chips.inputs['Detail'].default_value=2
    mask=n.new('ShaderNodeMath');mask.operation='MULTIPLY';l.new(ramp.outputs[0],mask.inputs[0]);l.new(chips.outputs['Fac'],mask.inputs[1])
    wear=n.new('ShaderNodeMixRGB');wear.inputs[2].default_value=(.43,.36,.20,1);l.new(mask.outputs[0],wear.inputs[0]);l.new(grime.outputs[0],wear.inputs[1]);l.new(wear.outputs[0],s.inputs['Base Color'])
    records.append({'object':name,'resolution':512,'AO':maps['AO'].image.filepath_raw,'curvature':maps['curvature'].image.filepath_raw,'method':'Cycles AO and Geometry Pointiness emission'})
bpy.ops.file.pack_all();bpy.ops.wm.save_as_mainfile(filepath=str(M/'finished.blend'))
(out/'manifest.json').write_text(json.dumps(records,indent=2));print('BAKED',len(records),'AO/curvature pairs')
# Frozen rest-camera UVs follow the true geometry during animation.
from bpy_extras.object_utils import world_to_camera_view
from mathutils import Vector
bpy.context.view_layer.update();tex=bpy.data.images.load(str(ASSETS/'projection.png'))
view=sc.camera.rotation_euler.to_matrix() @ Vector((0,0,1));projection=[]
for o in list(bpy.data.objects):
    if o.type!='MESH' or not o.name.startswith('GEO-'):continue
    # Shared tread geometry must receive independent camera UVs in its own rest position.
    if o.data.users>1:o.data=o.data.copy()
    parent=o.parent
    moving_gear=False
    while parent:
        moving_gear=moving_gear or 'phase' in parent or 'wheel' in parent
        parent=parent.parent
    mesh=o.data;old=mesh.uv_layers.active.name if mesh.uv_layers.active else None
    uv=mesh.uv_layers.new(name='PaintingProjection');confidence=mesh.color_attributes.new(name='Projection confidence',type='FLOAT_COLOR',domain='CORNER')
    nm=o.matrix_world.to_3x3().inverted().transposed()
    for poly in mesh.polygons:
        facing=max(0,min(1,((nm @ poly.normal).normalized().dot(view)-.02)/.35))
        for index in poly.loop_indices:
            v=mesh.vertices[mesh.loops[index].vertex_index];p=world_to_camera_view(sc,sc.camera,o.matrix_world @ v.co)
            uv.data[index].uv=(p.x,p.y);confidence.data[index].color=(facing,facing,facing,1)
    mat=mesh.materials[0].copy();mat.name=o.name+' projected';mesh.materials.clear();mesh.materials.append(mat)
    n=mat.node_tree.nodes;l=mat.node_tree.links;s=n.get('Principled BSDF')
    if old:
        buv=n.new('ShaderNodeUVMap');buv.uv_map=old
        for node in list(n):
            if node.type=='TEX_IMAGE' and not node.inputs['Vector'].is_linked:l.new(buv.outputs[0],node.inputs['Vector'])
    original=s.inputs['Base Color'].links[0].from_socket
    coord=n.new('ShaderNodeUVMap');coord.uv_map='PaintingProjection'
    im=n.new('ShaderNodeTexImage');im.image=tex;im.extension='CLIP';l.new(coord.outputs[0],im.inputs['Vector'])
    conf=n.new('ShaderNodeVertexColor');conf.layer_name='Projection confidence'
    mask=n.new('ShaderNodeMath');mask.operation='MULTIPLY';l.new(conf.outputs['Color'],mask.inputs[0]);l.new(im.outputs['Alpha'],mask.inputs[1])
    weight=n.new('ShaderNodeMath');weight.operation='MULTIPLY';weight.inputs[1].default_value=.28 if moving_gear else .94;l.new(mask.outputs[0],weight.inputs[0])
    mix=n.new('ShaderNodeMixRGB');l.new(weight.outputs[0],mix.inputs[0]);l.new(original,mix.inputs[1]);l.new(im.outputs['Color'],mix.inputs[2]);l.new(mix.outputs[0],s.inputs['Base Color'])
    # A painting includes baked light: preserve it using a partial emission mixture.
    emit=n.new('ShaderNodeEmission');l.new(mix.outputs[0],emit.inputs['Color'])
    fac=n.new('ShaderNodeMath');fac.operation='MULTIPLY';fac.inputs[1].default_value=.20 if moving_gear else .64;l.new(mask.outputs[0],fac.inputs[0])
    blend=n.new('ShaderNodeMixShader');l.new(fac.outputs[0],blend.inputs[0]);l.new(s.outputs[0],blend.inputs[1]);l.new(emit.outputs[0],blend.inputs[2]);l.new(blend.outputs[0],n.get('Material Output').inputs['Surface'])
    projection.append(o.name)
bpy.ops.file.pack_all();bpy.ops.wm.save_as_mainfile(filepath=str(M/'finished.blend'))
(M/'projection.json').write_text(json.dumps({'meshes':projection,'strength':{'static':.94,'rotating_gear':.28},'emission_fraction':{'static':.64,'rotating_gear':.20},'hidden_fill':'generated painted-fill.png, frozen-camera facing fade','source':'projection.png'},indent=2))
log(f'Finished materials: three actual AO/curvature bake pairs, generated unseen paint, {len(projection)} genuine projected meshes; all textures packed.')
